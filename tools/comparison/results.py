from __future__ import annotations

import csv
import json
from pathlib import Path

from common import Case, ContractError, write_json
from timing import summarize

METRIC_FIELDS = ["n_good", "n_anomaly", "image_auroc", "pixel_auroc", "aupro030",
                 "regions", "foreground_pixels", "background_pixels"]


def summarize_run(run: Path) -> None:
    if not (run / "manifest.json").is_file():
        raise ContractError(f"Not an initialized comparison run: {run}")
    methods = ["anomalib4j", "padim", "patchcore"]
    categories = ["bottle", "metal_nut"]
    rows = []
    for method in methods:
        for category in categories:
            directory = run / method / category
            unified = directory / "metrics-unified.json"
            row: dict[str, object] = {"method": method, "category": category, "status": None,
                                      "metric_source": None, "reason": None}
            row.update({field: None for field in METRIC_FIELDS})
            if not unified.exists():
                row["reason"] = "metrics-unified.json missing; evaluation not run"
            else:
                document = json.loads(unified.read_text(encoding="utf-8"))
                row["metric_source"] = "metrics-unified.json"
                row["status"] = document.get("status")
                for field in METRIC_FIELDS:
                    row[field] = document.get(field)
                if row["status"] != "verified":
                    row["reason"] = "metrics status " + str(row["status"])
            rows.append(row)
    summary_fields = ["method", "category", "status", *METRIC_FIELDS, "metric_source", "reason"]
    with (run / "summary-by-category.csv").open("x", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=summary_fields)
        writer.writeheader()
        writer.writerows(rows)
    macro_rows = []
    for method in methods:
        verified = [row for row in rows if row["method"] == method and row["status"] == "verified"]
        macro: dict[str, object] = {"method": method, "verified_categories": len(verified), "reason": None}
        for field in ["image_auroc", "pixel_auroc", "aupro030"]:
            values = [row[field] for row in verified if isinstance(row[field], (int, float))]
            macro[field + "_macro"] = round(sum(values) / len(values), 12) if values else None
        if not verified:
            macro["reason"] = "no verified metrics for this method"
        macro_rows.append(macro)
    macro_fields = ["method", "verified_categories", "image_auroc_macro", "pixel_auroc_macro", "aupro030_macro", "reason"]
    with (run / "macro-summary.csv").open("x", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=macro_fields)
        writer.writeheader()
        writer.writerows(macro_rows)
    lines = ["# Comparison result", "",
             "Generated by `run.py summarize` over the frozen layout. Per-category values in",
             "`summary-by-category.csv` are authoritative; macro values are the arithmetic mean over verified",
             "categories only. Missing measurement = `null` cell plus a reason in the same row, never 0.",
             "Interpretation and the final claim remain operator-owned.", "",
             "| method | category | status | Image AUROC | Pixel AUROC | AUPRO030 | reason |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for row in rows:
        cells = ["null" if row[field] is None else str(row[field])
                 for field in ["method", "category", "status", "image_auroc", "pixel_auroc", "aupro030", "reason"]]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    (run / "RESULT.md").write_text("\n".join(lines), encoding="utf-8")


def python_latency(case: Case) -> None:
    rows = []
    for path in sorted(case.directory.glob("latency-process-*.csv")):
        with path.open(encoding="utf-8") as stream:
            rows.extend(csv.DictReader(stream))
    with (case.directory / "latency-samples.csv").open("x", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=["process", "pid", "region", "iteration", "elapsed_ns"])
        writer.writeheader()
        writer.writerows(rows)
    summary = {"status": "smoke_only" if case.smoke else "measured", "unit": "us", "sampler": "perf_counter_ns every call; pooled samples, linear quantiles; no timer subtraction",
               "detection": "N/A: native model produces score and map together", "regions": {}}
    for region in ["native_full", "full_resolution"]:
        selected = [row for row in rows if row["region"] == region]
        processes = sorted({row["process"] for row in selected})
        summary["regions"][region] = {"aggregate": summarize([float(row["elapsed_ns"]) / 1000 for row in selected]),
                                     "processes": {process: summarize([float(row["elapsed_ns"]) / 1000 for row in selected if row["process"] == process]) for process in processes}}
    write_json(case.directory / "latency-summary.json", summary)


def jmh_latency(case: Case) -> None:
    files = [case.directory / "jmh.json"] if (case.directory / "jmh.json").exists() else sorted(case.directory.glob("jmh-process-*.json"))
    document = [benchmark for path in files for benchmark in json.loads(path.read_text(encoding="utf-8"))]
    rows = []
    summary = {"status": "smoke_only" if case.smoke else "measured", "unit": "us", "sampler": "JMH SampleTime rawDataHistogram weighted observations; histogram bins are not individually timed every invocation", "regions": {}}
    grouped = {}
    for benchmark in document:
        grouped.setdefault(benchmark["benchmark"], []).append(benchmark["primaryMetric"])
    for name, primaries in grouped.items():
        region = name.rsplit(".", 1)[1]
        primary = primaries[0]
        per_fork = {}
        all_values = []
        histograms = [fork for metric in primaries for fork in metric["rawDataHistogram"]]
        for fork, iterations in enumerate(histograms):
            values = []
            for iteration, bins in enumerate(iterations):
                for elapsed, count in bins:
                    rows.append([fork, region, iteration, elapsed, count])
                    values.extend([float(elapsed)] * int(count))
            per_fork[str(fork)] = summarize(values)
            all_values.extend(values)
        summary["regions"][region] = {"jmh_mean_us": primary["score"], "jmh_percentiles": primary["scorePercentiles"],
                                     "weighted_histogram_aggregate": summarize(all_values), "processes": per_fork}
    with (case.directory / "latency-samples.csv").open("x", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(["fork", "region", "iteration", "elapsed_us", "count"])
        writer.writerows(rows)
    write_json(case.directory / "latency-summary.json", summary)
